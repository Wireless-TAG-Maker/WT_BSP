static const char *TAG = "gc2145_sensor";

static esp_err_t gc2145_write(gc2145_sensor_t *sensor, uint8_t reg, uint8_t value)
{
    const uint8_t data[] = {reg, value};
    return i2c_master_transmit(sensor->device, data, sizeof(data), GC2145_TIMEOUT_MS);
}

static esp_err_t gc2145_read(gc2145_sensor_t *sensor, uint8_t reg, uint8_t *value)
{
    return i2c_master_transmit_receive(sensor->device, &reg, sizeof(reg), value, 1,
                                       GC2145_TIMEOUT_MS);
}

static esp_err_t gc2145_read_u16(gc2145_sensor_t *sensor, uint8_t reg, uint16_t *value)
{
    uint8_t high;
    uint8_t low;
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, reg, &high), TAG, "read 0x%02x", reg);
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, reg + 1, &low), TAG, "read 0x%02x", reg + 1);
    *value = ((uint16_t)high << 8) | low;
    return ESP_OK;
}

static esp_err_t gc2145_write_u16(gc2145_sensor_t *sensor, uint8_t reg, uint16_t value)
{
    ESP_RETURN_ON_ERROR(gc2145_write(sensor, reg, value >> 8), TAG, "write 0x%02x", reg);
    return gc2145_write(sensor, reg + 1, value & 0xff);
}

static esp_err_t gc2145_read_exposure(gc2145_sensor_t *sensor, uint16_t *value)
{
    /* AEC can update between SCCB transfers. Retry if the high byte changes. */
    for (unsigned int attempt = 0; attempt < 3; attempt++) {
        uint8_t high_before;
        uint8_t low;
        uint8_t high_after;
        ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0x03, &high_before), TAG, "read exposure high");
        ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0x04, &low), TAG, "read exposure low");
        ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0x03, &high_after), TAG, "verify exposure high");
        if ((high_before & 0x1f) == (high_after & 0x1f)) {
            *value = ((uint16_t)(high_after & 0x1f) << 8) | low;
            return ESP_OK;
        }
    }
    return ESP_ERR_INVALID_STATE;
}

static esp_err_t gc2145_restore_page0(gc2145_sensor_t *sensor, esp_err_t result)
{
    esp_err_t restore = gc2145_write(sensor, GC2145_REG_RESET_RELATED, 0);
    return result == ESP_OK ? restore : result;
}

static esp_err_t gc2145_output_enable(gc2145_sensor_t *sensor, bool enable)
{
    ESP_RETURN_ON_ERROR(gc2145_write(sensor, GC2145_REG_RESET_RELATED, 0), TAG, "select page 0");
    ESP_RETURN_ON_ERROR(gc2145_write(sensor, GC2145_REG_OUTPUT_ENABLE, enable ? 0x0f : 0),
                        TAG, "set DVP output");
    return ESP_OK;
}

static esp_err_t gc2145_write_table(gc2145_sensor_t *sensor,
                                    const gc2145_reginfo_t *table, size_t count)
{
    for (size_t i = 0; i < count; i++) {
        if (table[i].reg == GC2145_REG_DELAY) {
            /* Round up, including the possible partial first scheduler tick. */
            vTaskDelay(pdMS_TO_TICKS(table[i].val) + 1);
            continue;
        }
        /* Keep DVP output stopped until capture and the final window are ready. */
        uint8_t value = table[i].reg == GC2145_REG_OUTPUT_ENABLE ? 0 : table[i].val;
        ESP_RETURN_ON_ERROR(gc2145_write(sensor, table[i].reg, value), TAG,
                            "register table failed at index %u", (unsigned int)i);
    }
    return ESP_OK;
}

static esp_err_t gc2145_apply_720p_timing(gc2145_sensor_t *sensor)
{
    /* Geometry and AEC values from Linux's GC2145 720p mode:
     * https://github.com/torvalds/linux/blob/master/drivers/media/i2c/gc2145.c
     * Keep the Espressif table's DVP clock gating, polarity and full-pixel readout. */
    static const gc2145_reginfo_t geometry[] = {
        {0xfe, 0x00},
        {0x09, 0x00}, {0x0a, 0xf0}, /* Raw row start 240. */
        {0x0b, 0x00}, {0x0c, 0xa0}, /* Raw column start 160. */
        {0x0d, 0x02}, {0x0e, 0xe0}, /* Raw height 736. */
        {0x0f, 0x05}, {0x10, 0x10}, /* Raw width 1296. */
        {0x90, 0x01},
        {0x91, 0x00}, {0x92, 0x00}, {0x93, 0x00}, {0x94, 0x00},
        {0x95, 0x02}, {0x96, 0xd0}, /* Output height 720. */
        {0x97, 0x05}, {0x98, 0x00}, /* Output width 1280. */
        /* AEC's initial exposure stays within the cropped row cadence. */
        {0x03, 0x02}, {0x04, 0xb2},
    };
    ESP_RETURN_ON_ERROR(gc2145_write_table(sensor, geometry, sizeof(geometry) / sizeof(geometry[0])),
                        TAG, "set 720p sensor window");
    /* The hardware JPEG encoder consumes UYVY directly. */
    ESP_RETURN_ON_ERROR(gc2145_write(sensor, GC2145_REG_P0_OUTPUT_FORMAT, 0), TAG, "select UYVY");
    ESP_RETURN_ON_ERROR(gc2145_write(sensor, 0xfa, GC2145_720P_DVP_DIVIDER), TAG, "set DVP divider");
    ESP_RETURN_ON_ERROR(gc2145_write(sensor, 0xf8, GC2145_720P_PLL_MODE2), TAG, "set 720p PLL");
    ESP_RETURN_ON_ERROR(gc2145_write_u16(sensor, 0x05, GC2145_720P_HBLANK), TAG, "set 720p HBLANK");
    ESP_RETURN_ON_ERROR(gc2145_write_u16(sensor, 0x07, GC2145_720P_VBLANK), TAG, "set 720p VBLANK");
    ESP_RETURN_ON_ERROR(gc2145_write(sensor, GC2145_REG_RESET_RELATED, 1), TAG, "select AEC page");
    ESP_RETURN_ON_ERROR(gc2145_write_u16(sensor, 0x25, GC2145_720P_AEC_STEP), TAG, "set 720p anti-flicker step");
    for (size_t i = 0; i < 4; i++) {
        ESP_RETURN_ON_ERROR(gc2145_write_u16(sensor, 0x27 + 2 * i, GC2145_720P_EXPOSURE_CAP), TAG, "set 720p exposure cap");
    }
    return gc2145_restore_page0(sensor, ESP_OK);
}

static esp_err_t gc2145_readback_registers(gc2145_sensor_t *sensor, gc2145_sensor_readback_t *readback)
{
    gc2145_sensor_readback_t state = {0};
    ESP_RETURN_ON_ERROR(gc2145_write(sensor, GC2145_REG_RESET_RELATED, 0), TAG, "select page 0");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0xf0, &state.pid), TAG, "read PID");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x91, &state.y), TAG, "read output Y");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x93, &state.x), TAG, "read output X");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x95, &state.height), TAG, "read output height");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x97, &state.width), TAG, "read output width");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x0d, &state.raw_height), TAG, "read raw height");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x0f, &state.raw_width), TAG, "read raw width");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x05, &state.hblank), TAG, "read horizontal blanking");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x07, &state.vblank), TAG, "read vertical blanking");
    ESP_RETURN_ON_ERROR(gc2145_read_exposure(sensor, &state.exposure), TAG, "read exposure");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x11, &state.sh_delay), TAG, "read shutter delay");
    state.sh_delay &= 0x03ff;
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0xb6, &state.aec_enabled), TAG, "read AEC enable");
    state.aec_enabled &= 1;
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0xf7, &state.pll_mode1), TAG, "read PLL mode 1");
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0xf8, &state.pll_mode2), TAG, "read PLL mode 2");
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0xf9, &state.clock_mode), TAG, "read clock mode");
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0xfa, &state.clock_divider), TAG, "read clock divider");
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0xfd, &state.scalar_mode), TAG, "read scalar mode");
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0x18, &state.analog_mode), TAG, "read analog mode");
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0x84, &state.output_format), TAG, "read output format");
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0x86, &state.sync_mode), TAG, "read sync mode");
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0xf2, &state.output_enable), TAG, "read output enable");
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0x90, &state.crop_enable), TAG, "read crop enable");
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0x99, &state.subsample), TAG, "read subsampling");
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0x9a, &state.subsample_mode), TAG, "read subsampling mode");
    for (size_t i = 0; i < sizeof(state.subsample_pattern); i++) {
        ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0x9b + i, &state.subsample_pattern[i]),
                            TAG, "read subsampling pattern 0x%02x", (unsigned int)(0x9b + i));
    }
    ESP_RETURN_ON_ERROR(gc2145_write(sensor, GC2145_REG_RESET_RELATED, 1), TAG, "select AEC page");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x25, &state.anti_flicker_step), TAG, "read anti-flicker step");
    state.anti_flicker_step &= 0x1fff;
    for (size_t i = 0; i < 4; i++) {
        ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x27 + 2 * i, &state.exposure_levels[i]),
                            TAG, "read exposure level %u", (unsigned int)i);
        state.exposure_levels[i] &= 0x1fff;
    }
    ESP_RETURN_ON_ERROR(gc2145_read(sensor, 0x3c, &state.max_exp_level), TAG, "read AEC max level register");
    *readback = state;
    return ESP_OK;
}

esp_err_t gc2145_sensor_readback(gc2145_sensor_t *sensor, gc2145_sensor_readback_t *readback)
{
    if (sensor == NULL || sensor->device == NULL || readback == NULL) {
        return ESP_ERR_INVALID_ARG;
    }
    gc2145_sensor_readback_t state;
    esp_err_t ret = gc2145_readback_registers(sensor, &state);
    ret = gc2145_restore_page0(sensor, ret);
    if (ret == ESP_OK) {
        *readback = state;
    }
    return ret;
}

static esp_err_t gc2145_verify(gc2145_sensor_t *sensor)
{
    gc2145_sensor_readback_t state;
    ESP_RETURN_ON_ERROR(gc2145_sensor_readback(sensor, &state), TAG, "read configured mode");
    uint16_t row_start, col_start;
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x09, &row_start), TAG, "read 720p raw row start");
    ESP_RETURN_ON_ERROR(gc2145_read_u16(sensor, 0x0b, &col_start), TAG, "read 720p raw column start");
    const bool matches = state.pid == GC2145_PID && state.width == 1280 && state.height == 720 &&
                         state.x == 0 && state.y == 0 && state.raw_width == 1296 &&
                         state.raw_height == 736 && row_start == 240 && col_start == 160 &&
                         state.hblank == GC2145_720P_HBLANK &&
                         state.vblank == GC2145_720P_VBLANK && state.pll_mode1 == 0x1d &&
                         state.pll_mode2 == GC2145_720P_PLL_MODE2 && state.output_format == 0 &&
                         state.clock_divider == GC2145_720P_DVP_DIVIDER && state.output_enable == 0 &&
                         state.crop_enable == 1 && state.subsample == 0x11 &&
                         state.sync_mode == 0x02 && state.scalar_mode == 0 && state.aec_enabled &&
                         state.anti_flicker_step == GC2145_720P_AEC_STEP && state.exposure_levels[0] == GC2145_720P_EXPOSURE_CAP &&
                         state.exposure_levels[1] == GC2145_720P_EXPOSURE_CAP && state.exposure_levels[2] == GC2145_720P_EXPOSURE_CAP &&
                         state.exposure_levels[3] == GC2145_720P_EXPOSURE_CAP;
    if (!matches) {
        ESP_LOGE(TAG, "720p readback mismatch: PID=%04x raw=%ux%u output=%ux%u format=%02x "
                  "PLL=%02x/%02x FA=%02x HB=%u VB=%u sh_delay=%u exposure=%u sync=%02x",
             (unsigned)state.pid, (unsigned)state.raw_width, (unsigned)state.raw_height,
             (unsigned)state.width, (unsigned)state.height, (unsigned)state.output_format,
             (unsigned)state.pll_mode1, (unsigned)state.pll_mode2, (unsigned)state.clock_divider,
             (unsigned)state.hblank, (unsigned)state.vblank, (unsigned)state.sh_delay,
             (unsigned)state.exposure, (unsigned)state.sync_mode);
    }
    return matches ? ESP_OK : ESP_ERR_INVALID_STATE;
}

esp_err_t gc2145_sensor_init(gc2145_sensor_t *sensor, i2c_master_bus_handle_t bus)
{
    if (sensor == NULL || bus == NULL) {
        return ESP_ERR_INVALID_ARG;
    }
    if (sensor->device != NULL) {
        return ESP_ERR_INVALID_STATE;
    }
    memset(sensor, 0, sizeof(*sensor));
    const i2c_device_config_t config = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = GC2145_ADDRESS,
        .scl_speed_hz = GC2145_I2C_SPEED_HZ,
    };
    esp_err_t ret = i2c_master_bus_add_device(bus, &config, &sensor->device);
    if (ret != ESP_OK) {
        return ret;
    }

    uint16_t pid = 0;
    ret = gc2145_write(sensor, GC2145_REG_RESET_RELATED, 0);
    if (ret == ESP_OK) {
        ret = gc2145_read_u16(sensor, 0xf0, &pid);
    }
    if (ret == ESP_OK && pid != GC2145_PID) {
        ESP_LOGE(TAG, "expected GC2145, received PID=0x%04x", pid);
        ret = ESP_ERR_NOT_FOUND;
    }
    if (ret != ESP_OK) {
        goto fail;
    }
    sensor->detected = true;
    const gc2145_reginfo_t *table = gc2145_dvp_8bit_20Minput_1600x1200_rgb565_be_13fps;
    ret = gc2145_write_table(sensor, table, sizeof(gc2145_dvp_8bit_20Minput_1600x1200_rgb565_be_13fps) / sizeof(*table));
    if (ret == ESP_OK) {
        ret = gc2145_apply_720p_timing(sensor);
    }
    if (ret == ESP_OK) {
        ret = gc2145_output_enable(sensor, false);
    }
    if (ret == ESP_OK) {
        /* Allow buffered timing registers to settle before checking readback. */
        vTaskDelay(pdMS_TO_TICKS(120) + 1);
        ret = gc2145_verify(sensor);
    }
    if (ret != ESP_OK) {
        goto fail;
    }
    sensor->configured = true;
    ESP_LOGI(TAG, "GC2145 UYVY 1280x720, output stopped");
    return ESP_OK;

fail:
    /* Preserve a handle if stopping/removing fails; caller must retry deinit. */
    if (gc2145_sensor_deinit(sensor) != ESP_OK) {
        ESP_LOGE(TAG, "sensor cleanup incomplete after init error");
    }
    return ret;
}

esp_err_t gc2145_sensor_set_stream(gc2145_sensor_t *sensor, bool enable)
{
    if (sensor == NULL || sensor->device == NULL) {
        return ESP_ERR_INVALID_ARG;
    }
    if (!sensor->configured) {
        return ESP_ERR_INVALID_STATE;
    }
    return gc2145_output_enable(sensor, enable);
}

esp_err_t gc2145_sensor_deinit(gc2145_sensor_t *sensor)
{
    if (sensor == NULL) {
        return ESP_ERR_INVALID_ARG;
    }
    if (sensor->device == NULL) {
        memset(sensor, 0, sizeof(*sensor));
        return ESP_OK;
    }
    if (sensor->detected) {
        ESP_RETURN_ON_ERROR(gc2145_output_enable(sensor, false), TAG, "stop sensor before removal");
    }
    sensor->configured = false;
    ESP_RETURN_ON_ERROR(i2c_master_bus_rm_device(sensor->device), TAG, "remove I2C device");
    memset(sensor, 0, sizeof(*sensor));
    return ESP_OK;
}
